<h2>Trường hợp được đổi/trả</h2>
<ul>
  <li>Sản phẩm bị lỗi do sản xuất (bao bì rách, hỏng, ẩm mốc).</li>
  <li>Giao sai sản phẩm, sai quy cách, sai số lượng.</li>
  <li>Sản phẩm hết hạn sử dụng hoặc gần hết hạn (dưới 3 tháng) tại thời điểm giao hàng.</li>
</ul>

<h2>Trường hợp KHÔNG áp dụng đổi/trả</h2>
<ul>
  <li>Sản phẩm đã qua sử dụng, đã mở seal (trừ lỗi NSX).</li>
  <li>Bao bì ngoài bị trầy xước nhỏ do quá trình vận chuyển (không ảnh hưởng chất lượng sản phẩm bên trong).</li>
  <li>Quá 7 ngày kể từ ngày nhận hàng.</li>
  <li>Không có bằng chứng về tình trạng lỗi/hỏng.</li>
  <li>Lý do đổi trả là "không thích" hoặc "thay đổi sở thích" (chúng tôi khuyến khích đặt hàng mẫu nhỏ trước).</li>
</ul>

